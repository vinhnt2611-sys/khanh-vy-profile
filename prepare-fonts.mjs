import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const root=path.dirname(fileURLToPath(import.meta.url));
const url='https://fonts.googleapis.com/css2?family=Be+Vietnam+Pro:wght@400;500;600;700;800&display=swap';
const res=await fetch(url,{headers:{'User-Agent':'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130.0.0.0 Safari/537.36'}});
if(!res.ok)throw new Error('Font stylesheet failed: '+res.status);
const css=await res.text();
fs.writeFileSync(path.join(root,'fonts-source.css'),css);
const matches=[...css.matchAll(/\/\*\s*([^*]+?)\s*\*\/\s*(@font-face\s*\{[^}]+\})/g)];
const wanted=matches.filter(m=>['latin','latin-ext','vietnamese'].includes(m[1].trim()));
if(wanted.length!==15 || !wanted.some(m=>m[1]==='vietnamese'))throw new Error('Unexpected font subsets: '+wanted.map(m=>m[1]));
const faces=await Promise.all(wanted.map(async m=>{
  const subset=m[1].trim(),rule=m[2];
  const family=rule.match(/font-family:\s*'([^']+)'/)[1];
  const weight=rule.match(/font-weight:\s*([^;]+)/)[1].trim();
  const fontUrl=rule.match(/url\(([^)]+)\)/)[1];
  const fontResponse=await fetch(fontUrl);if(!fontResponse.ok)throw new Error('Font failed '+fontUrl);
  const bytes=Buffer.from(await fontResponse.arrayBuffer());
  if(bytes.subarray(0,4).toString()!=='wOF2')throw new Error('Expected WOFF2');
  fs.mkdirSync(path.join(root,'fonts'),{recursive:true});
  fs.writeFileSync(path.join(root,'fonts',`${family.toLowerCase().replace(/ /g,'-')}-${weight}-${subset}.woff2`),bytes);
  console.log(family,weight,subset,bytes.length);
  return `/* ${family}: ${subset} */\n`+rule.replace(fontUrl,`data:font/woff2;base64,${bytes.toString('base64')}`);
}));
const licenses=await Promise.all(['bevietnampro'].map(async family=>{const response=await fetch(`https://raw.githubusercontent.com/google/fonts/main/ofl/${family}/OFL.txt`);if(!response.ok)throw new Error('License unavailable');return `${family.toUpperCase()}\n${await response.text()}`;}));
fs.writeFileSync(path.join(root,'fonts','OFL.txt'),licenses.join('\n\n'));
fs.writeFileSync(path.join(root,'fonts.css'),'/* Embedded font licenses\n'+licenses.join('\n\n').replace(/\*\//g,'* /')+'\n*/\n'+faces.join('\n'));
fs.writeFileSync(path.join(root,'fonts','source.txt'),'Font: Be Vietnam Pro, used throughout the HTHT interface and supporting Vietnamese.\nSource: '+url+'\nGoogle Fonts, SIL Open Font License.\n');
